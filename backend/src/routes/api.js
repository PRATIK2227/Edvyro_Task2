import { Router } from 'express';
import { asyncHandler } from '../utils/asyncHandler.js';
import { authenticate, authorize } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';
import * as c from '../controllers/controllers.js';
import { registerSchema,loginSchema,createInternshipSchema,updateInternshipSchema,idSchema,listSchema,applySchema,statusSchema } from '../validators/schemas.js';
const router = Router();
const wrap = (fn) => asyncHandler(fn);
router.post('/auth/register',validate(registerSchema),wrap(c.register));
router.post('/auth/login',validate(loginSchema),wrap(c.login));
router.get('/auth/me',authenticate,wrap(c.me));
router.get('/internships',validate(listSchema),wrap(c.listJobs));
router.get('/internships/:id',validate(idSchema),wrap(c.getJob));
router.post('/internships',authenticate,authorize('recruiter','admin'),validate(createInternshipSchema),wrap(c.createJob));
router.patch('/internships/:id',authenticate,authorize('recruiter','admin'),validate(updateInternshipSchema),wrap(c.updateJob));
router.delete('/internships/:id',authenticate,authorize('recruiter','admin'),validate(idSchema),wrap(c.deleteJob));
router.post('/internships/:id/apply',authenticate,authorize('student'),validate(applySchema),wrap(c.apply));
router.get('/applications/mine',authenticate,authorize('student'),wrap(c.myApplications));
router.get('/applications/received',authenticate,authorize('recruiter','admin'),wrap(c.receivedApplications));
router.patch('/applications/:id/status',authenticate,authorize('recruiter','admin'),validate(statusSchema),wrap(c.changeApplicationStatus));
router.get('/bookmarks',authenticate,authorize('student'),wrap(c.getBookmarks));
router.put('/bookmarks/:internshipId',authenticate,authorize('student'),wrap(async (req,res) => {
  const { internshipId } = req.params;
  if (!/^[0-9a-f-]{36}$/i.test(internshipId)) return res.status(400).json({success:false,error:{code:'INVALID_ID',message:'Invalid internship ID'}});
  await c.saveBookmark(req,res);
}));
router.delete('/bookmarks/:internshipId',authenticate,authorize('student'),wrap(c.unsaveBookmark));
router.get('/dashboard',authenticate,wrap(c.getDashboard));
router.get('/health',wrap(async (_req,res) => res.json({success:true,status:'ok',timestamp:new Date().toISOString()})));
export default router;
